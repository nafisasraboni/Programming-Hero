//subtraction
function sub(num1,num2){
    console.log("Given numbers are: ",num1,",",num2);
    const subb = num1-num2;
    console.log("Substraction of these numbers = ",subb);
}
sub(1110984747, 65967988);

//multiplication
function mul(num1,num2,num3,num4){
    console.log("Given numbers are: ",num1,",",num2,",",num3,",",num4);
    const mull = num1*num2*num3*num4;
    console.log("Multiplication of these numbers = ",mull);
}
mul(11,65,7,89);

